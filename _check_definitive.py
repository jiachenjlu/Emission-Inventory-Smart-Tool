from core.temporal import TemporalProfile
import datetime

tp = TemporalProfile(r'D:\ai agent\智能清单工具\data\templates')

hourly = pd.read_csv(r'D:\ai agent\智能清单工具\data\templates\hourly.csv')
weekly = pd.read_csv(r'D:\ai agent\智能清单工具\data\templates\weekly.csv')
monthly = pd.read_csv(r'D:\ai agent\智能清单工具\data\templates\monthly.csv')

import calendar

year, month = 2025, 6
source = 'IN'
days_in_month = calendar.monthrange(year, month)[1]

# ISAT.M temporal factor for each hour
isat_factors = []
for day in range(1, days_in_month + 1):
    ymd = datetime.datetime(year, month, day)
    weekday = ymd.weekday()
    
    weeksum = []
    for d in range(1, days_in_month + 1):
        ymdtst = datetime.datetime(year, month, d)
        weektst = ymdtst.weekday()
        weekfactortst = weekly.loc[weekly['weekly'] == float(weektst)][source].mean()
        weeksum.append(weekfactortst)
    weeksumsing = np.array(weeksum) / np.array(weeksum).sum()
    
    weekfactor = weeksumsing[day - 1]
    mouthfactor = monthly.loc[monthly['monthly'] == float(month)][source].mean()
    
    for hour in range(24):
        hourfactor = hourly.loc[hourly['hourly'] == float(hour)][source].mean()
        val = mouthfactor * weekfactor * hourfactor
        isat_factors.append(val)

isat_factors = np.array(isat_factors)

# Our temporal factor for each hour
start_dt = datetime.datetime(year, month, 1, 0)
end_dt = datetime.datetime(year, month, days_in_month, 23)
our_factors = tp.build_temporal_matrix_range(start_dt, end_dt, source, inputtype='month')

